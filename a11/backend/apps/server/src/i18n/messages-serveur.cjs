function langueDeRequete(req) {
  const choisie = req && req.headers ? String(req.headers['x-funesterie-language'] || '').trim() : '';
  if (choisie) return normalizeLanguageCode(choisie, 'fr');
  return req ? resolveUserLanguage(req, 'fr') : 'fr';
}

/** Le message `cle` dans la langue de la requête, `{0}`… remplacés par `valeurs`. */
function messageServeur(req, cle, ...valeurs) {
  const langue = langueDeRequete(req);
  const modele = (MESSAGES[langue] && MESSAGES[langue][cle]) || MESSAGES.fr[cle];
  if (modele == null) return cle;
  return String(modele).replace(/\{(\d+)\}/g, (_tout, n) => (valeurs[n] != null ? String(valeurs[n]) : ''));
}

module.exports = { MESSAGES, langueDeRequete, messageServeur };
